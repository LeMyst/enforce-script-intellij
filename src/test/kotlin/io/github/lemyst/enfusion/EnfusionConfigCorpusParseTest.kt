package io.github.lemyst.enfusion

import com.intellij.openapi.util.text.StringUtil
import com.intellij.psi.PsiErrorElement
import com.intellij.psi.TokenType
import com.intellij.psi.tree.TokenSet
import com.intellij.psi.util.PsiTreeUtil
import com.intellij.testFramework.ParsingTestCase
import io.github.lemyst.enfusion.cfg.EnfusionConfigFileType
import io.github.lemyst.enfusion.cfg.EnfusionConfigParserDefinition
import io.github.lemyst.enfusion.cfg.psi.impl.EnCfgClassMixin
import java.io.File
import java.nio.charset.StandardCharsets
import java.nio.file.Files
import java.nio.file.Path
import java.nio.file.Paths
import kotlin.streams.toList

/**
 * Every `config.cpp` and `mod.cpp` that can be found, parsed and checked four ways.
 *
 * The fourth check is the one that matters and is new here: **the number of classes that came out is
 * compared against a count of `class` in the raw text.** The other corpus tests assert only that
 * there is no `PsiErrorElement` and that the text round-trips, and that pair is structurally blind to
 * a rule which *over-consumes* — the parser recovers by absorbing the rest of the file, producing no
 * error and losing no text. That is exactly how `typedef array<Class> TClassArray;` hid the loss of
 * `class set` and `class map` behind a green 2,811-file script corpus test. Counting what came out is
 * the cheapest check that would have caught it.
 *
 * Several roots on purpose: the mod's configs are hand-written (comments, `//` inside arrays), the
 * 349 Expansion ones are the largest third-party sample available and the only source of `+=`, and
 * the 207 under `P:\DZ` are machine-generated by the de-rapifier and are where scientific notation
 * and deeply nested arrays come from. No single tree exercises the grammar.
 *
 * Skips when no root is present, so a machine without a `P:` drive stays green.
 */
class EnfusionConfigCorpusParseTest :
    ParsingTestCase("", "cpp", EnfusionConfigParserDefinition()) {

    override fun getTestDataPath(): String = ""

    override fun skipSpaces(): Boolean = false

    override fun includeRanges(): Boolean = false

    override fun setUp() {
        super.setUp()
        // Forces the Kotlin `object` to initialise, which is what associates the file type with its
        // language. In production `plugin.xml` instantiates it at startup.
        EnfusionConfigFileType.name
    }

    fun testConfigCorpusParsesCleanly() {
        val roots = System.getProperty("enfusion.config.roots").orEmpty()
            .split(';')
            .map { it.trim() }
            .filter { it.isNotEmpty() && File(it).isDirectory }
        if (roots.isEmpty()) {
            log("no config roots present, skipping")
            return
        }

        val paths = roots.flatMap { root ->
            Files.walk(Paths.get(root)).use { stream ->
                stream.filter { path ->
                    val name = path.toString().replace('\\', '/')
                    // `.claude/worktrees` holds duplicate checkouts of the same configs.
                    !name.contains("/.claude/") &&
                        (name.endsWith("/config.cpp", ignoreCase = true) ||
                            name.endsWith("/mod.cpp", ignoreCase = true))
                }.toList()
            }
        }

        val failures = mutableListOf<String>()
        val badChars = TokenSet.create(TokenType.BAD_CHARACTER)
        var lines = 0
        var appends = 0
        var forwards = 0
        var classes = 0
        var oversized = 0
        val t0 = System.nanoTime()

        log("parsing ${paths.size} files from ${roots.joinToString(", ")}")

        paths.forEachIndexed { i, path ->
            val text = read(path)
            // The platform refuses PSI above `SingleRootFileViewProvider`'s intelligence limit and
            // hands back plain text, so these files are not parsed in a real IDE either -- vanilla's
            // `DZ/sounds/hpp/config.cpp` is 9.2 MB and `DZ/weapons/melee/config.cpp` is 2.5 MB.
            // Skipping them here matches the product rather than papering over it.
            if (text.length > TOO_LARGE) {
                oversized++
                return@forEachIndexed
            }
            lines += text.count { it == '\n' }
            if (text.contains("[] +=") || text.contains("[]+=")) appends++

            val psi = createPsiFile("corpus$i.cpp", text)
            psi.node

            val error = PsiTreeUtil.findChildOfType(psi, PsiErrorElement::class.java)
            if (error != null) {
                val line = StringUtil.offsetToLineNumber(text, error.textOffset) + 1
                failures += "$path:$line  ${error.errorDescription}"
            }
            if (psi.text != text) {
                failures += "$path  TEXT MISMATCH (${psi.textLength} vs ${text.length})"
            }
            if (psi.node.getChildren(badChars).isNotEmpty()) failures += "$path  BAD_CHARACTER"

            val declared = PsiTreeUtil.findChildrenOfType(psi, EnCfgClassMixin::class.java)
            classes += declared.size
            forwards += declared.count { it.isForwardDeclaration() }
            val expected = CLASS_IN_TEXT.findAll(stripComments(text)).count()
            if (declared.size != expected) {
                failures += "$path  CLASS COUNT ${declared.size} parsed vs $expected in text"
            }
        }

        val ms = (System.nanoTime() - t0) / 1_000_000
        log("parsed ${paths.size} files / $lines lines in ${ms}ms (${lines * 1000L / maxOf(ms, 1)} lines/s)")
        log("$classes classes, of which $forwards forward declarations; $appends file(s) used `[] +=`")
        if (oversized > 0) log("$oversized file(s) skipped as larger than the platform's PSI limit")

        // Each guards a rule that would otherwise be dead code no real input had ever reached. If a
        // root drops out of the configuration this test would still pass while silently covering less.
        assertTrue("no forward declaration parsed -- are the config roots configured?", forwards > 0)
        assertTrue("no `[] +=` parsed -- is the Expansion checkout in enfusionConfigRoots?", appends > 0)

        if (failures.isNotEmpty()) {
            log("FAILURES (${failures.size}), first 40:")
            failures.take(40).forEach { log("  $it") }
            fail("${failures.size} config corpus failures - see log above")
        }
    }

    private companion object {
        /** `SingleRootFileViewProvider`'s default intelligence limit. */
        const val TOO_LARGE = 2_500_000

        val CLASS_IN_TEXT = Regex("""(?<![A-Za-z0-9_])class\s+[A-Za-z_]""")
        val LINE_COMMENT = Regex("""//[^\r\n]*""")
        val BLOCK_COMMENT = Regex("""/\*.*?\*/""", RegexOption.DOT_MATCHES_ALL)
        // Must model the same string grammar as the lexer, backslash-is-not-an-escape included --
        // otherwise the stripper and the parser disagree about where a string ends and the class
        // count check starts reporting phantom mismatches.
        val STRING = Regex(""""(?:[^"\r\n]|"")*"""")
    }

    /**
     * Comments and strings removed before counting, since both legitimately contain the word
     * `class` — vanilla writes `displayName="class 3 helmet"` and mods comment out whole classes.
     */
    private fun stripComments(text: String): String =
        text.replace(BLOCK_COMMENT, " ").replace(LINE_COMMENT, " ").replace(STRING, "\"\"")

    private fun log(message: String) {
        println("[config] $message")
        System.out.flush()
    }

    private fun read(path: Path): String =
        try {
            Files.readString(path, StandardCharsets.UTF_8)
        } catch (e: Exception) {
            String(Files.readAllBytes(path), charset("windows-1252"))
        }
}
